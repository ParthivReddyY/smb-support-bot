// Turns kb/*.md into src/kb.generated.ts: one chunk per "## " section.
// Run after editing anything in kb/: `npm run kb`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const root = join(import.meta.dirname, "..");
const chunks = [];

for (const file of readdirSync(join(root, "kb")).filter((f) => f.endsWith(".md")).sort()) {
  const md = readFileSync(join(root, "kb", file), "utf8");
  const page = md.match(/^# (.+)$/m)?.[1]?.trim() ?? basename(file, ".md");
  const slug = basename(file, ".md");
  for (const block of md.split(/^## /m).slice(1)) {
    const [heading, ...body] = block.split("\n");
    const text = body.join(" ").replace(/\s+/g, " ").trim();
    if (!text) continue;
    const id = `${slug}--${heading.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}`;
    chunks.push({ id, page, section: heading.trim(), text });
  }
}

const ids = new Set(chunks.map((c) => c.id));
if (ids.size !== chunks.length) throw new Error("Duplicate section ids in kb/ — rename a heading.");

writeFileSync(
  join(root, "src", "kb.generated.ts"),
  `// Generated by scripts/build-kb.mjs from kb/*.md. Do not edit by hand.\n` +
    `export type Chunk = { id: string; page: string; section: string; text: string };\n` +
    `export const KB: Chunk[] = ${JSON.stringify(chunks, null, 2)};\n`,
);
console.log(`Wrote ${chunks.length} chunks from kb/.`);
